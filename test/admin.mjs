import test from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {setTimeout as pause} from 'node:timers/promises';
import {mkdtemp,rm} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {randomUUID} from 'node:crypto';
const cwd=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const base='http://127.0.0.1:43219';
const image='data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVQIHWP4z8DwHwAFgAI/ScL/nwAAAABJRU5ErkJggg==';
test('관리자 로그인, 승인된 프레임 저장/수정/삭제 및 사용자 목록',async t=>{
  const dir=await mkdtemp(path.join(os.tmpdir(),'momentcut-frames-'));
  t.after(()=>rm(dir,{recursive:true,force:true}));
  const child=spawn(process.execPath,['server.js'],{cwd,env:{...process.env,PORT:'43219',ADMIN_PASSWORD:'a-very-long-demo-admin-password',ADMIN_SESSION_SECRET:'test-secret-for-signing-admin-cookies-which-is-quite-long',FRAME_DATA_DIR:dir,SHARED_DIR:path.join(dir,'shares')}});
  t.after(()=>child.kill());
  let ready=false;
  for(let i=0;i<80;i++){await pause(60);try{if((await fetch(base+'/health')).ok){ready=true;break}}catch{}}
  assert.ok(ready,'테스트 서버 시작 실패');
  for(const p of ['/admin.html','/admin.js','/admin.css'])assert.equal((await fetch(base+p)).status,200);
  assert.equal((await fetch(base+'/api/admin?action=list')).status,401);
  const wrong=await fetch(base+'/api/admin?action=login',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({password:'incorrect'})});
  assert.equal(wrong.status,401);
  const right=await fetch(base+'/api/admin?action=login',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({password:'a-very-long-demo-admin-password'})});
  assert.equal(right.status,200);const cookie=right.headers.get('set-cookie');assert.match(cookie,/HttpOnly/);assert.match(cookie,/SameSite=Strict/);
  const auth={cookie:cookie.split(';')[0]};
  const session=await (await fetch(base+'/api/admin?action=session',{headers:auth})).json();assert.equal(session.authenticated,true);
  const frame={id:randomUUID(),name:'생일 프레임',count:4,orientation:'vertical',width:900,height:2600,color:'#ffeedd',textColor:'#222222',title:'HAPPY DAY',subtitle:'모두의 생일',titleSize:37,titleY:.93,subtitleY:.96,slots:[0,1,2,3].map(i=>({x:.1,y:.1+i*.19,w:.8,h:.17}))};
  const save=await fetch(base+'/api/admin?action=save',{method:'POST',headers:{...auth,'content-type':'application/json'},body:JSON.stringify({frame,imageData:image})});
  assert.equal(save.status,200,await save.text());
  const published=(await (await fetch(base+'/api/frames')).json()).frames;
  assert.equal(published.length,1);assert.equal(published[0].title,'HAPPY DAY');assert.ok(published[0].imageKey);
  const imageResponse=await fetch(`${base}/api/frame-image?id=${frame.id}`);assert.equal(imageResponse.status,200);assert.equal(imageResponse.headers.get('content-type'),'image/png');
  frame.title='다시 변경한 문구';const update=await fetch(base+'/api/admin?action=save',{method:'POST',headers:{...auth,'content-type':'application/json'},body:JSON.stringify({frame})});assert.equal(update.status,200);
  const updated=(await (await fetch(base+'/api/frames')).json()).frames[0];assert.equal(updated.title,'다시 변경한 문구');assert.equal(updated.imageKey,published[0].imageKey);
  const forbidden=await fetch(base+'/api/admin?action=delete',{method:'POST',headers:{...auth,origin:'http://malicious.example','content-type':'application/json'},body:JSON.stringify({id:frame.id})});assert.equal(forbidden.status,403);
  const deleted=await fetch(base+'/api/admin?action=delete',{method:'POST',headers:{...auth,'content-type':'application/json'},body:JSON.stringify({id:frame.id})});assert.equal(deleted.status,200);
  assert.equal((await (await fetch(base+'/api/frames')).json()).frames.length,0);
  const logout=await fetch(base+'/api/admin?action=logout',{method:'POST',headers:auth});assert.equal(logout.status,200);assert.match(logout.headers.get('set-cookie'),/Max-Age=0/);
});
